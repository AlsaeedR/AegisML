# EXECUTION ENDPOINT
# =========================================================

@app.post("/audit/execute")
def execute_planned_audit(
    audit_id: str = Form(...),
):
    """
    Continue the audit after explicit human approval.

    This endpoint executes the attack strategy prepared by
    /audit/plan and then invokes Agent 3.

    The resulting report is returned with status
    awaiting_gate_2 so the UI can require a final
    human report sign-off before download.
    """

    session = AUDIT_SESSIONS.get(
        audit_id
    )

    if not session:

        raise HTTPException(
            status_code=404,
            detail=(
                "Audit planning session "
                "not found or expired."
            ),
        )

    try:

        # -------------------------------------------------
        # Agent 2
        # Execute human-approved strategy
        # -------------------------------------------------

        agent_2_result = (
            _execute_agent_2_with_approved_plan(
                session
            )
        )

        # -------------------------------------------------
        # Agent 3
        # Risk Scoring & Reporting Agent
        # -------------------------------------------------

        reporting_result = (
            run_reporting_agent(
                agent_1_results=(
                    session[
                        "agent_1_result"
                    ]
                ),
                agent_2_results=(
                    agent_2_result
                ),
            )
        )

        # -------------------------------------------------
        # Return result for Gate 2 review
        # -------------------------------------------------

        return {
            "status": (
                "awaiting_gate_2"
            ),

            "audit_id": (
                audit_id
            ),

            "report": (
                reporting_result.get(
                    "final_report"
                )
            ),

            "deployment_context": (
                _deployment_context(
                    session[
                        "agent_1_result"
                    ]
                )
            ),

            "pipeline_graph": (
                session[
                    "agent_1_result"
                ].get(
                    "pipeline_graph",
                    {},
                )
            ),

            "pipeline_source": (
                session[
                    "pipeline_source"
                ]
            ),

            "attack_strategy_plan": (
                session[
                    "attack_strategy_plan"
                ]
            ),
        }

    except HTTPException:
        raise

    except Exception as exc:

        raise HTTPException(
            status_code=500,
            detail=str(exc),
        )

    finally:

        # Remove uploaded files after the dynamic audit
        # and final report have been generated.

        shutil.rmtree(
            session.get(
                "temp_dir",
                "",
            ),
            ignore_errors=True,
        )

        AUDIT_SESSIONS.pop(
            audit_id,
            None,
        )


# =========================================================
# LEGACY / FULL-AUDIT ENDPOINT
# =========================================================

@app.post("/audit")
def run_audit(
    pipeline_file: UploadFile = File(...),
    model_file: UploadFile = File(...),
    dataset_file: UploadFile = File(...),
    text_column: str = Form("text"),
    label_column: str = Form("label"),
):
    """
    Run the complete AegisML security audit without
    stopping at the human approval gates.

    This endpoint is retained for compatibility.

    The Streamlit HITL workflow uses:
        /audit/plan
        /audit/execute
    """

    # -----------------------------------------------------
    # Validate uploaded file types
    # -----------------------------------------------------

    _validate_upload_types(
        pipeline_file,
        model_file,
        dataset_file,
    )

    try:

        # Create a temporary directory for uploaded files.

        with tempfile.TemporaryDirectory() as temp_dir:

            pipeline_path = save_upload(
                pipeline_file,
                temp_dir,
            )

            model_path = save_upload(
                model_file,
                temp_dir,
            )

            dataset_path = save_upload(
                dataset_file,
                temp_dir,
            )

            # -------------------------------------------------
            # Read pipeline source code
            # -------------------------------------------------

            with open(
                pipeline_path,
                "r",
                encoding="utf-8",
            ) as file:

                python_code = (
                    file.read()
                )

            # -------------------------------------------------
            # Agent 1
            # Pipeline & Threat Model Agent
            # -------------------------------------------------

            agent_1_result = (
                run_pipeline_agent(
                    python_code
                )
            )

            # -------------------------------------------------
            # Agent 2
            # Vulnerability Testing Agent
            # -------------------------------------------------

            agent_2_result = (
                run_testing_agent(
                    agent_1_results=(
                        agent_1_result
                    ),
                    model_path=(
                        model_path
                    ),
                    dataset_path=(
                        dataset_path
                    ),
                    pipeline_path=(
                        pipeline_path
                    ),
                    text_column=(
                        text_column
                    ),
                    label_column=(
                        label_column
                    ),
                )
            )

            # -------------------------------------------------
            # Agent 3
            # Reporting Agent
            # -------------------------------------------------

            reporting_result = (
                run_reporting_agent(
                    agent_1_results=(
                        agent_1_result
                    ),
                    agent_2_results=(
                        agent_2_result
                    ),
                )
            )

            # -------------------------------------------------
            # Deployment context
            # -------------------------------------------------

            deployment_context = (
                _deployment_context(
                    agent_1_result
                )
            )

            # -------------------------------------------------
            # Return full result
            # -------------------------------------------------

            return {
                "status": (
                    "completed"
                ),

                "report": (
                    reporting_result.get(
                        "final_report"
                    )
                ),

                "deployment_context": (
                    deployment_context
                ),

                "pipeline_graph": (
                    agent_1_result.get(
                        "pipeline_graph",
                        {},
                    )
                ),

                "pipeline_source": (
                    python_code
                ),

                "attack_strategy_plan": (
                    agent_2_result.get(
                        "attack_strategy_plan"
                    )
                    or (
                        agent_2_result.get(
                            "structured_test_results"
                        )
                        or {}
                    ).get(
                        "attack_strategy_plan"
                    )
                    or {}
                ),
            }

    except HTTPException:
        raise

    except Exception as exc:

        raise HTTPException(
            status_code=500,
            detail=str(exc),
        )